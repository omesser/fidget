//! Settings form description: sections, rows, labels, and what they write.
//!
//! Split the same way the menu is: the form as data crosses the platform
//! boundary, and the AppKit window builds from that description. Linux and
//! Windows consume the same description when they ship, so labels cannot
//! drift.

use std::collections::HashMap;

use serde::Serialize;

use crate::consent;
use crate::dev_flags;
use crate::model;
use crate::settings::{BoolField, TextField};

/// Operations the settings window requests.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub enum RowOperation {
    Spawn,
    OpenMemory,
    WipeMemory,
    ClearKey,
    /// Put the generated BYO registration snippet on the system clipboard.
    CopyByoSnippet,
    /// Put the generated BYO raw token on the system clipboard (Hermes only).
    CopyByoToken,
    /// Send the whole AI tab as one patch.
    Apply,
    /// Redraw the AI tab from live state, writing nothing.
    Cancel,
    /// Throw the conversation in flight away and open a fresh one, leaving
    /// every row of the form where it is (#679).
    NewSession,
}

impl RowOperation {
    /// Stable wire representation for crossing the Rust/JS boundary.
    ///
    /// Step 5's `settings_event` command serializes `Outcome::Run` by calling
    /// this rather than exposing Debug text. The string matches the enum name
    /// in snake_case, which is what serde would derive, but explicit is cheaper
    /// than a serde derive on an enum the page does not need to round-trip.
    pub fn as_str(&self) -> &'static str {
        match self {
            Self::Spawn => "spawn",
            Self::OpenMemory => "open_memory",
            Self::WipeMemory => "wipe_memory",
            Self::ClearKey => "clear_key",
            Self::CopyByoSnippet => "copy_byo_snippet",
            Self::CopyByoToken => "copy_byo_token",
            Self::Apply => "apply",
            Self::Cancel => "cancel",
            Self::NewSession => "new_session",
        }
    }
}

/// One section of the settings form.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct FormSection {
    pub heading: String,
    pub rows: Vec<FormRow>,
    /// Short introductory text, always visible.
    pub comment: Option<String>,
    /// Extended explanation behind progressive disclosure ("What is this?").
    pub disclosure: Option<String>,
    /// Status information shown in a muted strip (env overrides, session state).
    pub status: Option<String>,
}

/// One row of the settings form, as data.
///
/// A row that writes carries the field it writes, so its kind and its field
/// have to agree: a `Checkbox` can only name a bool. That is what makes a
/// control writing nothing unrepresentable rather than merely tested (#287).
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
#[serde(tag = "type")]
pub enum FormRow {
    /// A checkbox that writes a bool to Settings.
    Checkbox {
        id: String,
        label: String,
        writes: BoolField,
        frozen: bool,
        /// Committed by Apply rather than on the tick.
        batched: bool,
        help: Option<String>,
        comment: Option<String>,
        /// Extended explanation behind progressive disclosure.
        disclosure: Option<String>,
        /// Status info (e.g., env override) shown in a muted strip.
        status: Option<String>,
    },
    /// An inspect-only text block showing current state.
    InspectBlock {
        id: String,
        label: Option<String>,
        help: Option<String>,
        /// Extended explanation behind progressive disclosure.
        disclosure: Option<String>,
        /// Status info shown in a muted strip.
        status: Option<String>,
    },
    /// An inspect-only wrapping label showing a path.
    InspectPath { id: String },
    /// A popup menu for choosing between options.
    Popup {
        id: String,
        label: Option<String>,
        writes: TextField,
        help: Option<String>,
        /// The choices. The Character popup's are `Live::installed`.
        options: Vec<String>,
        /// Read-only, for the same reason as `TextField::frozen`.
        frozen: bool,
        /// Committed by Apply rather than on pick, for the same reason as
        /// `TextField::batched`. The Completer source is the case that earned
        /// it: a pick used to kill a child before Cancel could put it back
        /// (#663).
        batched: bool,
        /// Extended explanation behind progressive disclosure.
        disclosure: Option<String>,
        /// Status info shown in a muted strip.
        status: Option<String>,
    },
    /// A multiline text field that writes to Settings.
    Multiline {
        id: String,
        label: Option<String>,
        writes: TextField,
        help: Option<String>,
        editable: bool,
        /// Extended explanation behind progressive disclosure.
        disclosure: Option<String>,
    },
    /// An editable text field that writes a string to Settings.
    TextField {
        id: String,
        label: Option<String>,
        placeholder: String,
        writes: TextField,
        /// A hint under the field, in the words every other row's `help` uses.
        ///
        /// A label says what the row is and a placeholder says what blank
        /// means; neither has room for what a value costs. The Completer
        /// timeout is the case that earned it: it budgets a Harness turn as
        /// well as an HTTP call, and nothing on screen said so (#447).
        help: Option<String>,
        /// Read-only: the value shown is not the user's to change. True when
        /// an exported variable owns the field, since `model::resolve` gives
        /// it the last word and would discard an edit made here (#272).
        frozen: bool,
        /// Committed by Apply. A partial endpoint or source edit would retarget
        /// the Completer and drop session history.
        batched: bool,
        /// Extended explanation behind progressive disclosure.
        disclosure: Option<String>,
        /// Status info shown in a muted strip.
        status: Option<String>,
    },
    /// A secure text field for passwords/keys.
    ///
    /// Always batched, so it carries no flag of its own. A secret cannot be
    /// compared to the file, so a secure field committed on blur retargets
    /// every single time — which is the cost `TextField::batched` exists to
    /// avoid, and there is no value of it that makes a blur-committed key
    /// correct (#279).
    SecureField {
        id: String,
        label: Option<String>,
        /// What the empty field says about the store: whether a key is set, or
        /// which variable overrides it. On the row rather than in `values`,
        /// the way `TextField` carries its own. The field's value stays empty,
        /// because the secret never leaves the store and a
        /// fingerprint sitting in it would be committed as a key on the next
        /// blur. #875.
        placeholder: String,
        writes: TextField,
        /// Read-only, for the same reason as `TextField::frozen`.
        frozen: bool,
        /// Status info shown in a muted strip.
        status: Option<String>,
    },
    /// A scrollable list of items with dismiss buttons.
    List {
        id: String,
        dismiss_label: String,
        help: Option<String>,
        /// Extended explanation behind progressive disclosure.
        disclosure: Option<String>,
    },
    /// A row of multiple controls (e.g., new instance spawn row).
    Composite {
        id: String,
        controls: Vec<CompositeControl>,
        help: Option<String>,
        /// Extended explanation behind progressive disclosure.
        disclosure: Option<String>,
    },
}

/// One control in a composite row.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
#[serde(tag = "type")]
pub enum CompositeControl {
    TextField {
        id: String,
        placeholder: String,
    },
    Popup {
        id: String,
        /// The choices, as `FormRow::Popup::options`.
        options: Vec<String>,
        /// Disabled, for the same reason as `FormRow::TextField::frozen`.
        frozen: bool,
        /// The row this popup is a shortcut for, or `None` for one read by
        /// the button beside it — which is what `new_instance` does.
        fills: Option<Shortcut>,
    },
    Button {
        id: String,
        label: String,
        /// Disabled, for the same reason as `FormRow::TextField::frozen`.
        frozen: bool,
    },
}

/// What a composite popup fills in, and how to read a title as a value.
///
/// A shortcut picker does not write its own title: `Custom` names no level,
/// and the Base URL picker writes a URL rather than a label. So a field alone
/// cannot serve it and the reading travels with the row it fills.
///
/// Whether a pick stages or saves is not declared here — it is the target
/// row's `batched`, so the shortcut and the field below it cannot disagree
/// about when the file is reached (#279).
#[derive(Clone, Copy, Debug, Serialize)]
pub struct Shortcut {
    /// The id of the text row filled in, whose `writes` is the field.
    pub row: &'static str,
    /// The value a picked title means, or `None` for Custom and for a title
    /// off the list — neither of which is a value to write over what the
    /// field holds.
    /// A function pointer is not data, so the shortcut crosses to
    /// JavaScript as the row it fills and nothing else.
    #[serde(skip)]
    pub value: fn(&str) -> Option<&'static str>,
}

/// By the row alone. A shortcut is the row it fills, and comparing the
/// reading beside it answers nothing: function pointer addresses are not
/// guaranteed unique.
impl PartialEq for Shortcut {
    fn eq(&self, other: &Self) -> bool {
        self.row == other.row
    }
}

impl Eq for Shortcut {}

/// One tab of the settings form, holding the sections that belong together.
///
/// The grouping is data here rather than a layout decision in the page,
/// so the webview tabs cannot disagree with the form about which heading sits
/// where.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct FormTab {
    pub title: String,
    pub sections: Vec<FormSection>,
}

/// The whole settings form as data: tabs, sections, rows, and what they write.
///
/// Everything here is owned, so this crosses a thread boundary. That is the
/// point of it: the description is built where the state lives, and the
/// platform window builds from it.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct FormDescription {
    pub tabs: Vec<FormTab>,
    /// What each button does, by control id. Only buttons: a writing row
    /// carries its own field, so no registry can disagree with one.
    #[serde(serialize_with = "sorted_operations")]
    pub operations: HashMap<String, RowOperation>,
}

/// A `HashMap` serializes in hash order, which differs run to run. The
/// committed fixtures are compared, so the keys leave in one order.
fn sorted_operations<S: serde::Serializer>(
    operations: &HashMap<String, RowOperation>,
    serializer: S,
) -> Result<S::Ok, S::Error> {
    operations
        .iter()
        .collect::<std::collections::BTreeMap<_, _>>()
        .serialize(serializer)
}

impl FormDescription {
    /// Every section, in tab order. For the parts of a renderer that want the
    /// rows and not the grouping, such as finding one row by id.
    pub fn sections(&self) -> impl Iterator<Item = &FormSection> + '_ {
        self.tabs.iter().flat_map(|tab| &tab.sections)
    }

    /// Whether the control carrying this id is the environment's rather than
    /// the user's. False for an id no control with a `frozen` field carries.
    ///
    /// Both windows ask this before they read a batched field: a frozen row is
    /// never dirty and never applies, because `model::resolve` would discard
    /// the edit (#272). Asked of the description rather than remembered beside
    /// the widget, so the two answers cannot drift.
    pub fn frozen(&self, id: &str) -> bool {
        self.sections()
            .flat_map(|section| &section.rows)
            .find_map(|row| match row {
                FormRow::Checkbox {
                    id: row_id, frozen, ..
                }
                | FormRow::TextField {
                    id: row_id, frozen, ..
                }
                | FormRow::SecureField {
                    id: row_id, frozen, ..
                }
                | FormRow::Popup {
                    id: row_id, frozen, ..
                } if row_id == id => Some(*frozen),
                FormRow::Composite { controls, .. } => {
                    controls.iter().find_map(|control| match control {
                        CompositeControl::Button {
                            id: control_id,
                            frozen,
                            ..
                        }
                        | CompositeControl::Popup {
                            id: control_id,
                            frozen,
                            ..
                        } if control_id == id => Some(*frozen),
                        _ => None,
                    })
                }
                _ => None,
            })
            .unwrap_or(false)
    }

    /// The boolean field the checkbox with this id writes.
    pub fn bool_write(&self, id: &str) -> Option<BoolField> {
        self.sections()
            .flat_map(|section| &section.rows)
            .find_map(|row| match row {
                FormRow::Checkbox {
                    id: row_id, writes, ..
                } if row_id == id => Some(*writes),
                _ => None,
            })
    }

    /// The text field the row with this id writes.
    pub fn text_write(&self, id: &str) -> Option<TextField> {
        self.sections()
            .flat_map(|section| &section.rows)
            .find_map(|row| match row {
                FormRow::TextField {
                    id: row_id, writes, ..
                }
                | FormRow::SecureField {
                    id: row_id, writes, ..
                }
                | FormRow::Multiline {
                    id: row_id, writes, ..
                }
                | FormRow::Popup {
                    id: row_id, writes, ..
                } if row_id == id => Some(*writes),
                _ => None,
            })
    }

    /// Whether the row with this id commits on Apply rather than on every
    /// tick, blur, or pick. Secure fields are always batched
    /// (`FormRow::SecureField`); an id that is not a value row stays false.
    pub fn batched(&self, id: &str) -> bool {
        self.sections()
            .flat_map(|section| &section.rows)
            .find_map(|row| match row {
                FormRow::Checkbox {
                    id: row_id,
                    batched,
                    ..
                }
                | FormRow::TextField {
                    id: row_id,
                    batched,
                    ..
                }
                | FormRow::Popup {
                    id: row_id,
                    batched,
                    ..
                } if row_id == id => Some(*batched),
                FormRow::SecureField { id: row_id, .. } if row_id == id => Some(true),
                _ => None,
            })
            .unwrap_or(false)
    }

    /// The row a composite popup is a shortcut for, and how to read its
    /// titles. `None` for every other control, popups included: a row that
    /// writes a field of its own answers `text_write` instead.
    pub fn shortcut(&self, id: &str) -> Option<Shortcut> {
        self.sections()
            .flat_map(|section| &section.rows)
            .find_map(|row| match row {
                FormRow::Composite { controls, .. } => {
                    controls.iter().find_map(|control| match control {
                        CompositeControl::Popup {
                            id: control_id,
                            fills,
                            ..
                        } if control_id == id => *fills,
                        _ => None,
                    })
                }
                _ => None,
            })
    }
}

